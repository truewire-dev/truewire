import importlib.util
import json
from pathlib import Path
import subprocess
import sys

import typer
from typing_extensions import Annotated

from .common import PROJECT_OPTION, resolve_project
from truewire.project import Project


class CodegenError(Exception):
  """Raised when code generation or its required finalization fails."""


MANIFEST_VERSION = 1
"""Version of the generated-file ownership manifest."""

GENERATED_BANNER = '# Generated by truewire — do not edit by hand.\n'
"""Prepended to every generated `.py`/`.pyi` file a project publishes."""


def generated_path(path: str) -> Path:
  """Validate and return one package-relative generated path.

  Raises:
    CodegenError: The path is empty, absolute, non-canonical, or escapes its package.
  """
  candidate = Path(path)
  if (
    not path
    or '\\' in path
    or candidate.is_absolute()
    or candidate == Path('.')
    or '..' in candidate.parts
    or candidate.as_posix() != path
  ):
    raise CodegenError(f'Unsafe generated path: {path!r}')
  return candidate


def generated_destination(root: Path, relative: Path) -> Path:
  """Resolve one generated path without allowing symlinks to escape its package."""
  destination = root / relative
  if not destination.resolve(strict=False).is_relative_to(root.resolve()):
    raise CodegenError(f'Generated path escapes package through a symlink: {relative}')
  current = root
  for part in relative.parts:
    current /= part
    if current.is_symlink():
      raise CodegenError(f'Generated path traverses a symlink: {relative}')
  return destination


def load_generated_manifest(path: Path) -> set[Path]:
  """Load and validate a generated-file ownership manifest.

  A missing manifest is a safe first-run bootstrap: codegen owns no existing files and
  therefore deletes nothing.

  Raises:
    CodegenError: The manifest is malformed, unsupported, or contains an unsafe path.
  """
  if not path.exists():
    return set()
  if not path.is_file():
    raise CodegenError(f'Codegen manifest is not a file: {path}')
  try:
    data = json.loads(path.read_text())
  except (OSError, json.JSONDecodeError) as exc:
    raise CodegenError(f'Could not read codegen manifest {path}: {exc}') from exc
  if not isinstance(data, dict):
    raise CodegenError(f'Invalid codegen manifest {path}: expected an object')
  version = data.get('version')
  if type(version) is not int or version != MANIFEST_VERSION:
    raise CodegenError(
      f'Unsupported codegen manifest version in {path}: {version!r}; '
      f'expected {MANIFEST_VERSION}'
    )
  files = data.get('files')
  if not isinstance(files, list) or any(not isinstance(item, str) for item in files):
    raise CodegenError(
      f'Invalid codegen manifest {path}: `files` must be a list of paths'
    )
  owned = [generated_path(item) for item in files]
  if len(set(owned)) != len(owned):
    raise CodegenError(f'Invalid codegen manifest {path}: duplicate file path')
  return set(owned)


def write_generated_manifest(path: Path, files: Iterable[Path]):
  """Atomically replace a generated-file ownership manifest."""
  content = (
    json.dumps(
      {
        'version': MANIFEST_VERSION,
        'files': [item.as_posix() for item in sorted(files)],
      },
      indent=2,
    )
    + '\n'
  )
  path.parent.mkdir(parents=True, exist_ok=True)
  temporary = path.with_suffix(f'{path.suffix}.tmp')
  try:
    temporary.write_text(content)
    temporary.replace(path)
  finally:
    if temporary.exists():
      temporary.unlink()


def reconcile_generated_output(
  root: Path,
  previous: set[Path],
  planned: set[Path],
) -> int:
  """Delete files the previous manifest owned and the current plan no longer emits.

  Returns:
    Number of files deleted. Already-absent owned files are harmless.
  """
  stale = previous - planned
  destinations = [
    (relative, generated_destination(root, relative)) for relative in sorted(stale)
  ]
  for _, destination in destinations:
    if destination.exists() and not destination.is_file():
      raise CodegenError(f'Owned generated path is not a file: {destination}')
  parents: set[Path] = set()
  deleted = 0
  for _, destination in destinations:
    if destination.is_file():
      destination.unlink()
      deleted += 1
    parents.update(
      parent
      for parent in destination.parents
      if parent != root and root in parent.parents
    )
  for parent in sorted(parents, key=lambda item: len(item.parts), reverse=True):
    try:
      parent.rmdir()
    except OSError:
      pass
  return deleted


def check_generated_manifest(
  root: Path,
  owned: set[Path],
  planned: set[Path],
) -> list[str]:
  """Report ownership and existence differences without changing generated output."""
  issues = [
    *(f'not recorded in manifest: {path}' for path in sorted(planned - owned)),
    *(f'no longer planned: {path}' for path in sorted(owned - planned)),
  ]
  destinations = [
    (relative, generated_destination(root, relative)) for relative in sorted(owned)
  ]
  for relative, destination in destinations:
    if not destination.exists():
      issues.append(f'owned file is missing: {relative}')
    elif not destination.is_file():
      issues.append(f'owned path is not a file: {relative}')
  return issues


def add_planned_file(planned: dict[Path, str], *, path: str, content: str):
  """Add one generated file to the plan, rejecting path collisions."""
  relative = generated_path(path)
  if relative in planned:
    raise CodegenError(f'Two generated outputs target the same file: {relative}')
  planned[relative] = content


def write_planned_files(root: Path, planned: Mapping[Path, str]):
  """Write every file in a validated generation plan, prefixing Python output with the
  contribution banner."""
  destinations = [
    (generated_destination(root, relative), relative, content)
    for relative, content in sorted(planned.items())
  ]
  for destination, relative, content in destinations:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if relative.suffix in ('.py', '.pyi'):
      content = GENERATED_BANNER + content
    destination.write_text(content)


def format_generated_files(root: Path, output_root: Path, files: Iterable[Path], *, config: Path):
  """Format only generated Python files with the project's Ruff config.

  Skips with a note when Ruff is not importable by the running interpreter -- formatting
  is a nicety over already-valid generated code, not a correctness step.
  """
  python_files = sorted(output_root / file for file in files if file.suffix == '.py')
  if not python_files:
    return
  if importlib.util.find_spec('ruff') is None:
    typer.echo('ruff is not installed; generated files were written unformatted.')
    return
  command = (
    sys.executable,
    '-m',
    'ruff',
    'format',
    '--config',
    str(config),
    *(str(path.relative_to(root)) for path in python_files),
  )
  formatted = subprocess.run(command, cwd=root, capture_output=True, text=True)
  if formatted.returncode != 0:
    detail = (
      formatted.stderr.strip()
      or formatted.stdout.strip()
      or f'exit code {formatted.returncode}'
    )
    raise CodegenError(
      f'Ruff formatting failed for {output_root.relative_to(root)}: {detail}'
    )


def typecheck_project(project: Project) -> bool:
  """Run Pyright over the project after generation, when the project asks for it.

  Runs when `[python].pyright` is true or a `pyrightconfig.json` sits at the project root,
  and Pyright is importable; otherwise returns `False` after printing why it was skipped.
  """
  root = project.root
  config = root / 'pyrightconfig.json'
  python = project.config.python
  wanted = config.is_file() or bool(python is not None and getattr(python, 'pyright', False))
  if not wanted:
    return False
  if importlib.util.find_spec('pyright') is None:
    typer.echo('pyright is not installed; skipping the post-generation type check.')
    return False
  command = (sys.executable, '-m', 'pyright', '--project', str(root))
  checked = subprocess.run(command, cwd=root, capture_output=True, text=True)
  if checked.stdout.strip():
    typer.echo(checked.stdout.strip())
  if checked.stderr.strip():
    typer.echo(checked.stderr.strip(), err=True)
  if checked.returncode != 0:
    raise CodegenError(f'Pyright failed for {project.name} (exit code {checked.returncode})')
  return True


def generate(
  language: str = typer.Argument('python', help='Target language. Only `python` is supported today.'),
  project: str | None = PROJECT_OPTION,
  verbose: int = typer.Option(0, '--verbose', '-v', count=True),
  delete: Annotated[
    bool,
    typer.Option('--delete', help='Delete only files owned by the existing manifest.'),
  ] = False,
  check: Annotated[
    bool,
    typer.Option('--check', help='Check the manifest against the current output plan.'),
  ] = False,
):
  """Generate the project's package from its spec, for the given language.

  Args:
    language: Codegen backend to generate with. Only `python` is supported today.
    project: Project directory (holding `truewire.toml`); the nearest one by default.
    verbose: Repeat for more detail: `-v` logs per-stage progress, `-vv` logs every file written.
    delete: Delete manifest-owned files without loading the backend or spec.
    check: Verify manifest ownership and file existence without writing.
  """
  from truewire.generation.types import ExternalReference

  from truewire.codegen.layout import (
    BackendUnavailable,
    aggregate_nodes,
    class_name,
    discover_schemas_files,
    endpoint_output,
    load_generator,
    load_schema_file,
    load_schemas,
    output_base,
    output_function,
    package_root,
    router_nodes,
    schemas_scope,
    skip_endpoint,
    skip_router,
  )
  from truewire.codegen.meta import META_MODULE, meta_module
  from truewire.plan.build import build_plan
  from truewire.codegen.python import (
    RouterChild,
    endpoint_transport,
    subtree_transport,
    surface_group_module,
  )
  from truewire.spec import Endpoint, load_router
  from truewire.spec.authoring import schemas_on_same_path_to_root

  def log(message: str, *, level: int = 1):
    if verbose >= level:
      typer.echo(message)

  def log_part(message: str):
    if verbose >= 2:
      print(message, end='', flush=True)

  def log_finish(message: str = ''):
    if verbose >= 2:
      print(message, flush=True)

  def progress(message: str):
    if verbose == 1:
      print(f'\r{message}', end='', flush=True)

  def progress_finish():
    if verbose == 1:
      print(flush=True)

  def endpoint_specs(loaded: Project) -> list[Path]:
    return sorted(loaded.endpoints_dir.rglob('endpoint.json'))

  def endpoint_mixin(endpoint: Endpoint) -> str:
    if endpoint.meta:
      return 'AuthEndpoint'
    op = endpoint.openapi
    if op and getattr(op, 'security', None):
      return 'AuthEndpoint'
    return 'Endpoint'

  def relative_import(from_file: Path, to_file: Path) -> str:
    from_parts = from_file.parts[:-1]
    to_parts = to_file.parts[:-1]
    common = 0
    while (
      common < min(len(from_parts), len(to_parts))
      and from_parts[common] == to_parts[common]
    ):
      common += 1
    up = len(from_parts) - common
    down = list(to_parts[common:])
    dots = '.' * (up + 1)
    target = down[:]
    if to_file.stem != '__init__':
      target.append(to_file.stem)
    suffix = '.'.join(target)
    return dots + suffix if suffix else dots

  if language != 'python':
    typer.echo(f'Unsupported language for now: {language}', err=True)
    raise typer.Exit(code=1)

  try:
    if delete and check:
      raise CodegenError('`--delete` and `--check` cannot be combined')
    loaded = resolve_project(project)
    root = loaded.root
    client_root = root
    client = loaded.name

    try:
      output_root = package_root(loaded)
    except BackendUnavailable as exc:
      raise CodegenError(str(exc))
    manifest_path = loaded.manifest_path(language)
    if delete:
      if not manifest_path.exists():
        raise CodegenError(
          f'Cannot delete generated files: missing manifest {manifest_path.relative_to(root)}'
        )
      owned = load_generated_manifest(manifest_path)
      deleted = reconcile_generated_output(output_root, owned, set())
      manifest_path.unlink()
      absent = len(owned) - deleted
      detail = f'; {absent} already absent' if absent else ''
      typer.echo(
        f'Deleted {deleted} generated files for {client}{detail}; removed '
        f'{manifest_path.relative_to(root)}.'
      )
      return

    log(f'[{client}] loading generator: {language}')
    try:
      generator = load_generator(loaded, language)
    except BackendUnavailable as exc:
      raise CodegenError(str(exc))
    generator.core_package = f'{output_root.name}.core'
    generator.project = loaded
    # Every `_resolve_core`/`router()` call reads `codegen_config` -- `None` for a legacy
    # project driven entirely by its own backend module (every branch this touches is
    # dead code for it), a loaded `PythonCodegenConfig` for a project generating through
    # the universal `Generator`.
    generator.codegen_config = loaded.config
    # The plan (`truewire plan`): every per-endpoint decision, computed once here and read
    # by `rpc_endpoint`/`stream_endpoint` instead of re-derived per call.
    log(f'[{client}] building plan')
    generator.plan = build_plan(loaded)
    log(f'[{client}] loading schemas')
    spec_root = loaded.spec_dir
    planned: dict[Path, str] = {}
    # `schemas_by_path` is only ever populated for the `codegen_config is not None`
    # (mechanized) branch below -- `generator._resolve_schemas` needs it per endpoint, to
    # merge every `schemas.json` scope visible from that endpoint's own directory. The
    # legacy per-project-backend branch has no such concept (nested scoping was never
    # implemented per backend) and keeps threading one flat `external['references']`
    # dict everywhere instead, exactly as it always has.
    schemas_by_path: dict[Path, Mapping[str, ExternalReference]] = {}
    if generator.codegen_config is None:
      # Legacy per-project backend (no `[python.cores]`): unchanged single-file behavior --
      # called unconditionally, even with an empty `schemas` map. A legacy backend
      # overrides `schemas()` itself, and a real override may act on more than its own
      # `schemas.json` input (`test_codegen_manifest_covers_every_
      # output_and_drives_the_next_cleanup`'s fake backend does exactly this, emitting a
      # file regardless of input), so skipping the call for an empty dict would silently
      # drop that output.
      schemas = load_schemas(client_root)
      generator.shared_schemas = schemas
      log(f'[{client}] generating shared schemas ({len(schemas)})')
      external = generator.schemas(schemas)
      flat_references = external['references']
      for file in external['files']:
        log(f'[{client}] plan schema file: {file["path"]}', level=2)
        add_planned_file(planned, path=file['path'], content=file['content'])
    else:
      # Mechanized project: one `schemas()` call per discovered
      # `schemas.json` file (the project root's own, plus any nested `spec/endpoints/**/
      # schemas.json` scope), `schemas_scope` set immediately before each call so the base
      # implementation knows which module/package to render into -- the identical
      # `router_context`-style stash `router()` already uses.
      flat_references = {}
      schemas_files = discover_schemas_files(loaded)
      root_schemas_path = loaded.schemas_path
      merged_shared_schemas: dict = {}
      ids_by_schemas_file: dict[Path, set[str]] = {}
      for schemas_path in schemas_files:
        file_schemas = load_schema_file(schemas_path)
        # Only a collision between two scopes on the same path to root is real -- an id
        # shared by two unrelated sibling scopes (`spot/schemas.json`,
        # `futures/schemas.json`) is never seen by any one endpoint's ancestor walk, so
        # nothing downstream can confuse the two. Reuses the identical predicate
        # `check_schemas_no_shadowing`/`_resolve_schemas` already get right rather than a
        # global, path-blind dict collision check, which used to reject that legitimate
        # case outright.
        for schema_id in file_schemas:
          for other_path, other_ids in ids_by_schemas_file.items():
            if schema_id in other_ids and schemas_on_same_path_to_root(
              schemas_path, other_path, root_schemas=root_schemas_path,
            ):
              raise CodegenError(
                f'schema id {schema_id!r} is declared in both {schemas_path} and '
                f'{other_path}; shadowing between scopes on the same path to root is '
                'refused -- run `truewire check` to catch this earlier next time'
              )
        ids_by_schemas_file[schemas_path] = set(file_schemas)
        merged_shared_schemas.update(file_schemas)
        generator.schemas_scope = schemas_scope(schemas_path, loaded)
        log(
          f'[{client}] generating shared schemas '
          f'({schemas_path.relative_to(client_root)}, {len(file_schemas)})'
        )
        es = generator.schemas(file_schemas)
        schemas_by_path[schemas_path] = es['references']
        for file in es['files']:
          log(f'[{client}] plan schema file: {file["path"]}', level=2)
          add_planned_file(planned, path=file['path'], content=file['content'])
      generator.schemas_scope = None
      generator.shared_schemas = merged_shared_schemas

    meta_source = meta_module(loaded.config.cores) if loaded.config is not None else None
    if meta_source is not None:
      log(f'[{client}] generating meta module')
      add_planned_file(planned, path=f'{META_MODULE}.py', content=meta_source)

    surface_groups = generator.surface_groups()
    if surface_groups:
      log(f'[{client}] generating surface groups ({len(surface_groups)})')
    for group in surface_groups:
      log(f'[{client}] surface group: {group["spec_dir"]} -> {group["path"]}', level=2)
      doc = load_router(loaded.endpoints_dir / group['spec_dir'])
      member_docs = {
        member['attr_name']: generator.router_doc(member['base'])
        for member in group['members']
      }
      add_planned_file(
        planned,
        path=group['path'],
        content=surface_group_module(group, doc, member_docs) + '\n',
      )

    endpoint_by_node: dict[tuple[str, tuple[str, ...]], Endpoint] = {}
    path_by_node: dict[tuple[str, tuple[str, ...]], Path] = {}
    class_by_node: dict[tuple[str, tuple[str, ...]], str] = {}
    transport_by_node: dict[tuple[str, tuple[str, ...]], str] = {}
    endpoints_root = loaded.endpoints_dir
    spec_files = endpoint_specs(loaded)
    endpoint_records = [
      (
        spec_file,
        Endpoint.model_validate_json(spec_file.read_text()),
      )
      for spec_file in spec_files
    ]
    endpoint_records = [
      (spec_file, endpoint)
      for spec_file, endpoint in endpoint_records
      # `absent` means nothing exists to import, ever -- filtered out up front, same as
      # always. `handwritten` (`skip_endpoint`-true but not `absent`) stays in the tree:
      # its file already exists at the conventional path a generated one would have used,
      # so it still needs a real node here for a router sharing its directory to mix it
      # in as a base -- only the per-endpoint loop below skips regenerating its content.
      # Filtering it out up front (the previous behavior) silently dropped it from every
      # such router's bases on every regen instead.
      if endpoint.surface is None or endpoint.surface.kind != 'absent'
    ]
    log(f'[{client}] generating endpoints ({len(spec_files)})')
    functions_by_base: dict[str, list[str]] = {}
    for spec_file, endpoint in endpoint_records:
      base = output_base(generator, endpoint)
      functions_by_base.setdefault(base, []).append(
        output_function(generator, endpoint, endpoint_path=spec_file, spec_root=spec_root)
      )
    aggregates_by_base = {
      base: aggregate_nodes(functions) for base, functions in functions_by_base.items()
    }
    router_nodes_by_base = {
      base: set(router_nodes(functions)) for base, functions in functions_by_base.items()
    }

    for index, (spec_file, endpoint) in enumerate(endpoint_records, start=1):
      progress(f'[{client}] endpoints {index}/{len(spec_files)}')
      endpoint_rel = spec_file.parent.relative_to(endpoints_root)
      log_part(f'[{client}] endpoint {index}/{len(spec_files)}: {endpoint_rel}')
      base = output_base(generator, endpoint)
      function = output_function(generator, endpoint, endpoint_path=spec_file, spec_root=spec_root)
      node = tuple(function.split('.'))
      # A node that is *also* a router node -- this endpoint's own directory carries an
      # endpoint-bearing descendant subdirectory too -- is refused outright (`docs/spec/
      # authoring.md` rule 16, standard S30), not composed: an earlier design redirected
      # this node's own leaf output one level deeper (to `<node>/<node[-1]>.py`) and
      # composed it as a base via a synthetic self-child, but that self-child could only
      # ever render as `__call__` (S29-forbidden), since a self-referential node's own
      # parent can never qualify as an `aggregate_nodes` parent. This raise replaces that
      # composition path -- the *primary*, real-CLI-reachable backstop; `router()`'s own
      # unconditional raise (`truewire.codegen.python.Generator.router`) is a second,
      # independent one for a direct caller that bypasses this loop. Without either, a
      # genuinely mixed directory would silently plan both `<node>.py` and
      # `<node>/__init__.py`, with Python's own import resolving the *package* and the
      # leaf module going dead -- the leaf endpoint dropped from the generated surface
      # with no error at all.
      if node in router_nodes_by_base[base]:
        raise CodegenError(
          f'{Path(base).joinpath(*node)}: this directory declares its own endpoint.json '
          '(function ' + repr('.'.join(node)) + ') and also has an endpoint-bearing '
          'descendant subdirectory -- a directory is a leaf endpoint or a router '
          'grouping, never both (docs/spec/authoring.md rule 16). Move its own '
          "endpoint.json (and examples/) into a new subdirectory named after its own "
          "function's last segment, matching a real sibling directory name."
        )
      out = endpoint_output(function, base=base)
      if (base, node) in endpoint_by_node:
        # Silently overwriting would be the worst failure mode of merging two channel
        # sets under one namespace: the second module wins and the first endpoint simply
        # disappears from the generated client, with every suite still green.
        raise CodegenError(
          f'Two endpoints generate the same module {out}: '
          f'{endpoint_by_node[(base, node)].function} and {endpoint.function}. '
          'Names merged into one namespace must be disjoint; rename one in its spec, '
          "or route it elsewhere from the backend's `output_function`."
        )
      endpoint_by_node[(base, node)] = endpoint
      path_by_node[(base, node)] = out
      transport_by_node[(base, node)] = endpoint_transport(endpoint)
      log_part(f' {endpoint.function}')
      parent = node[:-1]
      child_name = node[-1]
      requested_name = class_name(child_name)
      # Per-endpoint-directory reference resolution: a mechanized
      # project (`codegen_config` set) resolves only the schemas.json scopes actually
      # visible from *this* endpoint's own directory (`_resolve_schemas`'s ancestor
      # walk); a legacy per-project backend has no scoping concept and keeps the one flat
      # `references` map every endpoint always saw.
      endpoint_references = (
        flat_references
        if generator.codegen_config is None
        else generator._resolve_schemas(spec_file.parent, spec_root, schemas_by_path)
      )
      endpoint_class_name = generator.class_name(
        endpoint,
        endpoint_references,
        name=requested_name,
      )
      class_by_node[(base, node)] = endpoint_class_name
      method_name = generator.method_name(
        endpoint,
        parent=parent,
        child_name=child_name,
        is_aggregate_parent=parent in aggregates_by_base[base],
      )
      if skip_endpoint(generator, endpoint):
        # `handwritten`: the node above (path/class/transport) is real and used by any
        # router sharing its directory, but the file itself is hand-written -- regenerating
        # it here would overwrite what a person wrote.
        log_finish(f' -> {out} (hand-written, not regenerated)')
      else:
        add_planned_file(
          planned,
          path=out.as_posix(),
          content=generator.endpoint(
            endpoint,
            endpoint_references,
            class_name=endpoint_class_name,
            method_name=method_name,
            endpoint_dir=spec_file.parent,
          )
          + '\n',
        )
        log_finish(f' -> {out}')
    progress_finish()

    router_records: list[tuple[str, tuple[str, ...]]] = []
    for base, functions in functions_by_base.items():
      for node in router_nodes(functions):
        router_records.append((base, node))

    log(f'[{client}] generating routers ({len(router_records)})')
    for index, (base, node) in enumerate(router_records, start=1):
      # The true client root writes to `main.py`, never `__init__.py` -- the
      # hand-curated public export surface this plan must never overwrite. Only ever
      # fires for the one base representing a fully mechanized project's whole, unsplit
      # function tree (`base == ''`, `load_generator`'s own convention) -- a
      # still-hand-backed project's own bases (`spot`, `futures`, ...) are all non-empty
      # and unaffected.
      out = (
        Path('main.py') if base == '' and not node
        else Path(base).joinpath(*node, '__init__.py')
      )
      prefix_len = len(node)
      child_names = sorted(
        {
          parts[prefix_len]
          for node_base, parts in path_by_node
          if node_base == base
          and len(parts) > prefix_len
          and parts[:prefix_len] == node
        }
      )

      children: dict[str, RouterChild] = {}
      # A router node is never also a leaf (rule 16/S30) -- the endpoint loop
      # above already raises before this loop ever runs if `(base, node)` were in
      # `endpoint_by_node`, so there is no self-child to compose here; every child below
      # is a real subdirectory.
      for child_name in child_names:
        child_node = (*node, child_name)
        # A child that is itself a router node (has further descendants of its own) is
        # composed as a `kind: 'router'` child pointing at its own generated composite
        # class -- never as a bare `kind: 'endpoint'` leaf, which would multiply-inherit
        # only its leaf portion directly and silently drop everything under its own
        # subdirectory. Checked ahead of the plain leaf branch below.
        if child_node in router_nodes_by_base[base]:
          child_out = Path(base).joinpath(*child_node, '__init__.py')
          children[child_name] = {
            'import_path': relative_import(out, child_out),
            'class_name': class_name(child_name),
            'attr_name': child_name,
            'kind': 'router',
            'transport': subtree_transport(transport_by_node, base, child_node),
            'mixin': 'AuthRouter',
            'doc': load_router(loaded.endpoints_dir / Path(base, *child_node)),
            'spec_dir': loaded.endpoints_dir / Path(base, *child_node),
          }
        elif (base, child_node) in endpoint_by_node:
          endpoint = endpoint_by_node[(base, child_node)]
          child_out = path_by_node[(base, child_node)]
          children[child_name] = {
            'import_path': relative_import(out, child_out),
            'class_name': class_by_node[(base, child_node)],
            'attr_name': child_name,
            'kind': 'endpoint',
            'transport': transport_by_node[(base, child_node)],
            'mixin': endpoint_mixin(endpoint),
          }
        else:
          child_out = Path(base).joinpath(*child_node, '__init__.py')
          children[child_name] = {
            'import_path': relative_import(out, child_out),
            'class_name': class_name(child_name),
            'attr_name': child_name,
            'kind': 'router',
            'transport': subtree_transport(transport_by_node, base, child_node),
            'mixin': 'AuthRouter',
            'doc': load_router(loaded.endpoints_dir / Path(base, *child_node)),
            'spec_dir': loaded.endpoints_dir / Path(base, *child_node),
          }

      section = node[-1] if node else base
      label = f'{base}:{".".join(node) if node else base}'

      # `[python.extras]`: hand-written classes this router node folds in beyond what its own leaves generate --
      # substituting a generated leaf's own base (`replaces`) or adding one with no
      # spec leaf at all. Applied after `children` is otherwise final, so `replaces` can
      # target any real child built above, and before `skip_router`/`router()` render it.
      python_config = (
        generator.codegen_config.python if generator.codegen_config is not None else None
      )
      extras = (python_config.extras or {}).get('.'.join(node)) if python_config else None
      if extras:
        for extra in extras:
          extra_out = Path(base).joinpath(*node, f'{extra.file}.py')
          import_path = relative_import(out, extra_out)
          if extra.replaces is not None:
            if extra.replaces not in children:
              raise CodegenError(
                f'{label}: [python.extras] entry replaces={extra.replaces!r}, '
                'not a real child of this router node'
              )
            children[extra.replaces] = {
              **children[extra.replaces],
              'import_path': import_path,
              'class_name': extra.class_,
            }
          else:
            attr_name = extra.file.rsplit('.', 1)[-1]
            if attr_name in children:
              raise CodegenError(
                f'{label}: [python.extras] entry {attr_name!r} collides with a real child'
              )
            children[attr_name] = {
              'import_path': import_path,
              'class_name': extra.class_,
              'attr_name': attr_name,
              'kind': 'endpoint',
              'transport': 'http',
            }

      progress(f'[{client}] routers {index}/{len(router_records)}')
      log(f'[{client}] router {index}/{len(router_records)}: {label} -> {out}', level=2)
      generator.router_context = (base, node)
      if skip_router(generator, base, node):
        log_finish(f' -> {out} (hand-written, not regenerated)')
      else:
        add_planned_file(
          planned,
          path=out.as_posix(),
          content=generator.router(section, children) + '\n',
        )
    progress_finish()

    if check:
      if not manifest_path.exists():
        raise CodegenError(
          f'Cannot check generated files: missing manifest {manifest_path.relative_to(root)}'
        )
      owned = load_generated_manifest(manifest_path)
      issues = check_generated_manifest(output_root, owned, set(planned))
      if issues:
        typer.echo(f'Codegen manifest mismatch for {client}:', err=True)
        for issue in issues:
          typer.echo(f'- {issue}', err=True)
        raise typer.Exit(code=1)
      typer.echo(f'Codegen manifest matches {client} ({len(planned)} files).')
      return

    bootstrapping = not manifest_path.is_file()
    previous = load_generated_manifest(manifest_path)
    log(f'[{client}] reconciling generated files')
    reconcile_generated_output(output_root, previous, set(planned))
    write_planned_files(output_root, planned)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    write_generated_manifest(manifest_path, planned)
    if bootstrapping:
      typer.echo(
        f'Initialized {manifest_path.relative_to(root)}; preserved existing unowned files.'
      )
    log(f'[{client}] formatting generated files')
    format_generated_files(root, output_root, planned, config=loaded.ruff_config)
    log(f'[{client}] type-checking project')
    typecheck_project(loaded)
    typer.echo(f'Generated {client} ({language}) into {output_root.relative_to(root)}')
  except CodegenError as exc:
    typer.echo(str(exc), err=True)
    raise typer.Exit(code=1)
