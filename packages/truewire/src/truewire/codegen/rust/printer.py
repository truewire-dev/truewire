"""A deterministic printer for generated Rust that `rustfmt` leaves alone.

No formatter runs over the output, but `cargo fmt --check` runs over the generated crate
in CI, so the printer reproduces the few `rustfmt` decisions the emitted shapes can
trigger under its defaults: a signature that does not fit in `MAX_WIDTH` columns is laid
out one parameter per line, a struct literal whose body exceeds `STRUCT_LIT_WIDTH` goes
vertical, an attribute whose arguments exceed `ATTR_WIDTH` goes vertical, and `use`
declarations are sorted the way `rustfmt` sorts a contiguous group (plain paths before
brace lists, lowercase names before CamelCase before UPPER_CASE). Everything else is
emitted in the one form `rustfmt` produces for it: four-space indents, one struct field or
enum variant per line, trailing commas, a blank line between items.
"""
from collections.abc import Iterator
from contextlib import contextmanager

BANNER = '//! Generated by truewire — do not edit by hand.'
"""First line of every generated `.rs` file (a crate-level doc, so `cargo doc` shows it)."""

INDENT = '    '
MAX_WIDTH = 100
"""`rustfmt`'s default `max_width`."""
STRUCT_LIT_WIDTH = 18
"""`rustfmt`'s default `struct_lit_width`: the widest body it keeps on one line."""
ATTR_WIDTH = 70
"""`rustfmt`'s default `attr_fn_like_width`."""
CHAIN_WIDTH = 60
"""`rustfmt`'s default `chain_width`: the widest method chain it keeps on one line."""


class Writer:
  """Accumulates lines at the current indent; `render` joins them with one trailing newline."""

  def __init__(self, level: int = 0):
    self._lines: list[str] = []
    self._level = level

  @property
  def column(self) -> int:
    """Where a line written now starts."""
    return len(INDENT) * self._level

  def line(self, text: str = ''):
    """Emit one line (a blank one for an empty `text`, never trailing whitespace)."""
    self._lines.append(INDENT * self._level + text if text else '')

  def lines(self, text: str):
    for item in text.split('\n'):
      self.line(item)

  def blank(self):
    """Emit one blank line, unless the previous line already is one (or nothing was written)."""
    if self._lines and self._lines[-1] != '':
      self._lines.append('')

  @contextmanager
  def indented(self) -> Iterator[None]:
    self._level += 1
    try:
      yield
    finally:
      self._level -= 1

  @contextmanager
  def block(self, opener: str, closer: str = '}') -> Iterator[None]:
    """`opener` on its own line, the body one level in, then `closer`."""
    self.line(opener)
    with self.indented():
      yield
    self.line(closer)

  def doc(self, *paragraphs: str | None, inner: bool = False):
    """`///` (or `//!` when `inner`) lines from the non-empty paragraphs, blank-separated."""
    marker = '//!' if inner else '///'
    body: list[str] = []
    for paragraph in paragraphs:
      if paragraph is None or not paragraph.strip():
        continue
      if body:
        body.append('')
      body.extend(line.rstrip() for line in paragraph.strip().split('\n'))
    for item in body:
      self.line(f'{marker} {item}'.rstrip())

  def attribute(self, name: str, args: list[str]):
    """`#[name(args)]`, vertical when the arguments exceed `rustfmt`'s width."""
    joined = ', '.join(args)
    if len(joined) <= ATTR_WIDTH and self.column + len(f'#[{name}({joined})]') <= MAX_WIDTH:
      self.line(f'#[{name}({joined})]')
      return
    with self.block(f'#[{name}(', ')]'):
      for index, arg in enumerate(args):
        self.line(arg + (',' if index < len(args) - 1 else ''))

  def signature(self, head: str, params: list[str], tail: str):
    """`head(params) tail` on one line when it fits, else one parameter per line."""
    flat = f'{head}({", ".join(params)}){tail}'
    if self.column + len(flat) <= MAX_WIDTH:
      self.line(flat)
      return
    with self.block(f'{head}(', f'){tail}'):
      for param in params:
        self.line(f'{param},')

  def chain(self, prefix: str, root: str, elements: list[str], suffix: str = ''):
    """`prefix root.a.b() suffix` on one line when the chain is within `rustfmt`'s chain
    width, else one element per line under the root (which keeps its first element when
    it is a short bare statement root such as `self`)."""
    joined = f'{root}{"".join(elements)}'
    flat = f'{prefix}{joined}{suffix}'
    if len(joined) <= CHAIN_WIDTH and self.column + len(flat) <= MAX_WIDTH:
      self.line(flat)
      return
    rest = list(elements)
    head = f'{prefix}{root}'
    if not prefix and len(root) <= len(INDENT) and rest:
      head += rest.pop(0)
    self.line(head)
    with self.indented():
      for index, element in enumerate(rest):
        self.line(element + (suffix if index == len(rest) - 1 else ''))

  def struct_literal(self, prefix: str, name: str, fields: list[str], suffix: str = ''):
    """`prefix Name { fields } suffix` on one line when the body is within `rustfmt`'s
    struct-literal width, else one field per line."""
    body = ', '.join(fields)
    if not fields:
      self.line(f'{prefix}{name} {{}}{suffix}')
      return
    flat = f'{prefix}{name} {{ {body} }}{suffix}'
    if len(body) <= STRUCT_LIT_WIDTH and self.column + len(flat) <= MAX_WIDTH:
      self.line(flat)
      return
    with self.block(f'{prefix}{name} {{', f'}}{suffix}'):
      for field in fields:
        self.line(f'{field},')

  def render(self) -> str:
    out = '\n'.join(self._lines).rstrip('\n')
    return out + '\n'


def _ident_key(name: str) -> tuple[int, str]:
  """`rustfmt`'s order inside a brace list: `snake_case`, then `CamelCase`, then `UPPER`."""
  if name[:1].islower():
    return (0, name)
  if any(c.islower() for c in name):
    return (1, name)
  return (2, name)


class Imports:
  """The `use` declarations of one module, in three groups `rustfmt` sorts independently:
  `std`, external crates, `crate::`. Each group is one contiguous block."""

  def __init__(self):
    self._paths: dict[str, set[str]] = {}
    """Module path -> names imported from it (`{'Arc'}` for `use std::sync::Arc`)."""

  def add(self, path: str, name: str):
    self._paths.setdefault(path, set()).add(name)

  def module(self, path: str):
    """`use a::b;` (the last segment is the module itself)."""
    head, _, last = path.rpartition('::')
    self.add(head, last)

  def render(self) -> list[str]:
    groups: dict[int, list[tuple[tuple, str]]] = {0: [], 1: [], 2: []}
    for path, names in self._paths.items():
      group = 0 if path.split('::')[0] == 'std' else 2 if path.startswith('crate') else 1
      ordered = sorted(names, key=_ident_key)
      segments: list[tuple] = [(0, _ident_key(segment)) for segment in path.split('::')]
      if len(ordered) == 1:
        segments.append((0, _ident_key(ordered[0])))
        line = f'use {path}::{ordered[0]};'
      else:
        segments.append((1,))
        line = f'use {path}::{{{", ".join(ordered)}}};'
        if len(line) > MAX_WIDTH:
          line = '\n'.join([f'use {path}::{{', *_packed(ordered), '};'])
      groups[group].append((tuple(segments), line))
    out: list[str] = []
    for group in (0, 1, 2):
      lines = [line for _, line in sorted(groups[group])]
      if lines and out:
        out.append('')
      out.extend(lines)
    return out


def _packed(names: list[str]) -> list[str]:
  """`names` as `rustfmt` packs a brace list that overflows: as many per line as fit in
  `MAX_WIDTH`, each followed by a comma."""
  lines: list[str] = []
  current = INDENT
  for name in names:
    item = f'{name},'
    candidate = item if current == INDENT else f'{current} {item}'
    if current != INDENT and len(INDENT + candidate) > MAX_WIDTH:
      lines.append(current)
      current = INDENT + item
    else:
      current = INDENT + candidate if current == INDENT else candidate
  lines.append(current)
  return lines


