"""A deterministic printer for generated TypeScript.

No formatter runs over the output: every emitter writes through `Writer`, which owns the
two-space indent, blank-line discipline and JSDoc layout, so the same plan renders the same
bytes on every machine. Imports are rendered from a sorted `Imports` table for the same
reason.
"""
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import PurePosixPath

BANNER = '// Generated by truewire — do not edit by hand.'
"""First line of every generated `.ts` file."""

INDENT = '  '


class Writer:
  """Accumulates lines at the current indent; `render` joins them with one trailing newline."""

  def __init__(self):
    self._lines: list[str] = []
    self._level = 0

  def line(self, text: str = ''):
    """Emit one line (a blank one for an empty `text`, never trailing whitespace)."""
    self._lines.append(INDENT * self._level + text if text else '')

  def lines(self, text: str):
    """Emit several lines of already-joined text at the current indent."""
    for item in text.split('\n'):
      self.line(item)

  def blank(self):
    """Emit one blank line, unless the previous line already is one (or nothing was written)."""
    if self._lines and self._lines[-1] != '':
      self._lines.append('')

  @contextmanager
  def indented(self) -> Iterator[None]:
    self._level += 1
    try:
      yield
    finally:
      self._level -= 1

  @contextmanager
  def block(self, opener: str, closer: str = '}') -> Iterator[None]:
    """`opener` on its own line, the body one level in, then `closer`."""
    self.line(opener)
    with self.indented():
      yield
    self.line(closer)

  def jsdoc(self, *paragraphs: str | None, tags: list[str] = ()):  # type: ignore[assignment]
    """A `/** ... */` comment from non-empty paragraphs, then `@tag` lines."""
    body: list[str] = []
    for paragraph in paragraphs:
      if paragraph is None or not paragraph.strip():
        continue
      if body:
        body.append('')
      body.extend(line.rstrip() for line in paragraph.strip().replace('*/', '*\\/').split('\n'))
    tags = [tag for tag in tags if tag]
    if tags:
      if body:
        body.append('')
      body.extend(tags)
    if not body:
      return
    if len(body) == 1:
      self.line(f'/** {body[0]} */')
      return
    self.line('/**')
    for item in body:
      self.line(f' * {item}'.rstrip())
    self.line(' */')

  def render(self) -> str:
    out = '\n'.join(self._lines).rstrip('\n')
    return out + '\n'


class Imports:
  """Import table of one module: specifier -> names, each name flagged type-only or not.

  Rendered sorted, with `@truewire/core` first, then relative modules by path. A name
  imported both as a type and a value is imported once, as a value.
  """

  def __init__(self):
    self._names: dict[str, dict[str, bool]] = {}
    self._namespaces: dict[str, str] = {}

  def add(self, specifier: str, name: str, *, type_only: bool = False):
    entry = self._names.setdefault(specifier, {})
    entry[name] = entry.get(name, True) and type_only

  def namespace(self, specifier: str, alias: str):
    """`import * as alias from specifier`."""
    self._namespaces[specifier] = alias

  def render(self) -> list[str]:
    lines: list[str] = []
    for specifier in sorted(set(self._names) | set(self._namespaces), key=_import_order):
      if specifier in self._namespaces:
        lines.append(f'import * as {self._namespaces[specifier]} from {_string(specifier)}')
      names = self._names.get(specifier)
      if not names:
        continue
      if all(names.values()):
        rendered = ', '.join(sorted(names))
        lines.append(f'import type {{ {rendered} }} from {_string(specifier)}')
      else:
        rendered = ', '.join(
          f'type {name}' if type_only else name for name, type_only in sorted(names.items())
        )
        lines.append(f'import {{ {rendered} }} from {_string(specifier)}')
    return lines


def _import_order(specifier: str) -> tuple[int, str]:
  return (0 if not specifier.startswith('.') else 1, specifier)


def _string(value: str) -> str:
  from .names import string

  return string(value)


def relative_specifier(from_file: str, to_file: str) -> str:
  """The ESM specifier that imports `to_file` from `from_file` (both package-relative
  `.ts` paths): `./list.js`, `../types/index.js`."""
  source = PurePosixPath(from_file).parent
  target = PurePosixPath(to_file)
  source_parts = source.parts
  target_parts = target.parts[:-1]
  common = 0
  while (
    common < min(len(source_parts), len(target_parts))
    and source_parts[common] == target_parts[common]
  ):
    common += 1
  up = len(source_parts) - common
  down = [*target_parts[common:], target.stem + '.js']
  prefix = '../' * up if up else './'
  return prefix + '/'.join(down)


__all__ = ['BANNER', 'INDENT', 'Imports', 'Writer', 'relative_specifier']
